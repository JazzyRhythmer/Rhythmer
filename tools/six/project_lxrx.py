"""Project a small, varied LXR-02 palette into existing DRUM-X parameters.

This is a parameter translation, not an LXR DSP port or sound-identical clone.
The input kits have their own rights (Elixir assets/kits/README.md); their
presence in a GPL repository does not make those kits GPL-licensed.
No source .SND files or LXR waveform/sample tables are embedded in the result.
Run with an existing local Elixir checkout and the Rhythmer source directory.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

SELECTED = [1, 2, 3, 4, 6, 15, 20, 21, 30, 32, 39, 83]
# These six translated kick lanes need a low sine body and a quick downward
# sweep. Keep kit IDs, A/B morph behavior, and every other lane as projected.
# Values are DRUM-X pitch, sweep, decay, noise and colour.
KICK_TUNING = {
    1: (10, 69, 83, 4, 28),   # BADONKA: full tail
    6: (8, 50, 75, 3, 15),    # WOODSTYK: round, softer attack
    20: (15, 67, 66, 9, 42),  # 8_BIT: shorter and grainier
    30: (11, 78, 80, 6, 55),  # STEELBAR: firmer edge
    32: (9, 83, 56, 7, 34),   # JUNGLIST: short and punchy
    39: (13, 73, 62, 10, 28), # DRUMTRIX: compact mid punch
}
KICK_SINE_LP_SNAP = 16
LANES = [(0, False), (3, False), (3, False), (5, False), (5, True),
         (1, False), (2, False), (4, False)]

def clip(x, lo=0, hi=127):
    return max(lo, min(hi, round(x)))

def decay(d, slope):
    # Elixir gen_tables.py: EG_DEC and EG_SLOPE. Match the time to 1/e,
    # not the numeric slider, to DRUM-X's exponential 3ms * 2^(9*d/127).
    value = d / 127
    step = min(1., 2 * (1 - 1999 * value / (1 + 1998 * value)))
    a = (slope / 127 - .5) * 1.999
    k = 2 * a / (1 - a)
    y = math.exp(-1)
    v = y / (1 + k * (1 - y))
    tau = max(.003, min(1.536, (1 - v) / max(step, 1e-9) * 64 / 44100))
    return clip(127 / 9 * math.log2(tau / .003))

def project(data, lane):
    voice, opened = LANES[lane]
    coarse, fine = data[8 + voice * 2], data[9 + voice * 2]
    pitch = clip((coarse + (fine / 127 - .5) - 24) / .75)
    decpar = 61 if opened else 60 if voice == 5 else 50 + voice * 2
    dec = decay(data[decpar], data[62 + voice])
    sweep = clip(12 * math.log2(1 + 32 * (data[74 + voice] / 127) ** 2) / .375) if voice < 4 else 0
    fm = data[82 + voice * 2] if voice < 3 else data[31] if voice == 4 else data[35] if voice == 5 else 0
    mix = data[28] if voice == 3 else 0
    # The available oscillator ratios are 1, 1.47, 2.76. Select their nearest
    # log-frequency ratio, rather than pretending arbitrary LXR FM ratios fit.
    modnote = data[83 + voice * 2] if voice < 3 else data[29] if voice == 4 else data[33]
    ratio = 2 ** ((modnote - coarse) / 12)
    wave = 0 if fm < 8 else 1 + min(range(3), key=lambda j: abs(math.log2(ratio / [1, 1.47, 2.76][j])))
    cut = data[37 + voice] / 127
    hz = 44100 * .45 * (.1 * cut / (1 - .9 * cut))
    color = clip(127 * math.log(max(hz, 30) / 30) / math.log(16000 / 30))
    flt = 2 if data[191 + voice] == 1 else 1 if data[191 + voice] in (2, 3, 4, 5) else 0
    if voice >= 4:
        wave = 2 if ratio < 2 else 3
        mix = clip(20 + data[31 if voice == 4 else 35] * .4, 20, 70)
    if lane in (3, 4):
        # Keep the closed articulation short. Shared LXR hat voice becomes the
        # normal DRUM-X closed/open pair, with the existing hat choke behavior.
        mix = max(mix, 112); pitch = min(pitch, 104); color = max(color, 82); flt = 2
        if not opened: dec = min(dec, 24)
    if lane == 2:  # an eighth lane: snare-noise-derived clap, not an LXR voice
        mix = max(mix, 112); flt = 1; dec = min(dec, 66); sweep //= 3
    color = clip(color * .45 + fm * .55) if mix < 64 else color
    mode = wave | flt << 2 | (16 if lane in (0, 5, 6) else 0)
    if data[102 + voice] >= 48: mode |= 128
    return [mode, pitch, sweep, dec, mix, color]

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('elixir', type=Path)
    ap.add_argument('rhythmer', type=Path)
    args = ap.parse_args()
    rows = []
    for number in SELECTED:
        matches = list((args.elixir/'assets/kits/factory').glob(f'{number:03d}-*.SND'))
        if len(matches) != 1: raise SystemExit(f'Expected one source kit {number}')
        file = matches[0]; blob = file.read_bytes()
        if len(blob) < 255: raise SystemExit(f'Short kit: {file}')
        label = file.stem.split('-', 1)[1][:7]
        patches = [project(blob[8:255], lane) for lane in range(8)]
        if number in KICK_TUNING:
            patches[0] = [KICK_SINE_LP_SNAP, *KICK_TUNING[number]]
        rows.append(dict(name='LXR-X '+label, source=file.name, sha256=hashlib.sha256(blob).hexdigest(), lanes=patches))
    head = ('/* Generated by tools/six/project_lxrx.py. LXR-X re-voicings for DRUM-X,\n'
            ' * not LXR DSP. Factory reference: Erica Synths / Hrtl; input kit rights\n'
            ' * are separate from Elixir GPL code. See docs/research/LXR-X.md. */\n')
    src = args.rhythmer/'firmware/src'
    kits = []
    for r in rows:
        lanes = []
        for mode, *v in r['lanes']:
            a = '{'+','.join(map(str, v))+'}'
            lanes.append(f'{{{mode},{a},{a}}}')
        kits.append(' { .lane={'+','.join(lanes)+'},.lay={0},.snd={0} }, /* '+r['name']+' */')
    (src/'lxrx_kits.h').write_text(head+'\n'.join(kits)+'\n')
    (src/'lxrx_presets.h').write_text(head+''.join(' {"'+r['name']+'",{0,64,64,64,64,0,0,0},{0,100,127,100},0,TAG(DRUM),FX(0,0,0,0),PAT(12)},\n' for r in rows))
    docs = args.rhythmer.parent/'docs/research'; docs.mkdir(parents=True, exist_ok=True)
    (docs/'lxrx-projection.json').write_text(json.dumps(dict(count=len(rows), rows=rows), indent=2)+'\n')
    print(f'{len(rows)} LXR-X kits; {len(rows)*8} editable DRUM-X lane patches; no new DSP or samples')

if __name__ == '__main__': main()
