static void fmini_factory_load(unsigned slot, uint8_t *out)
{
    const uint8_t *row = FMNI_PACK[slot < FMINI_CURATED_COUNT ? slot : 0];
    unsigned bit = 0;
    for (unsigned field = 0; field < 32; ++field) {
        unsigned width = FMNI_W[field], value = 0;
        if (width) {
            unsigned byte = bit >> 3, shift = bit & 7u;
            value = row[byte];
            if (shift + width > 8u)
                value |= (unsigned)row[byte + 1] << 8;
            value = (value >> shift) & ((1u << width) - 1u);
        }
        out[field] = (uint8_t)(FMNI_LO[field] + value);
        bit += width;
    }
}
